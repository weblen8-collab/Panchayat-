    companion object {
        const val DEFAULT_PLACEHOLDER_URL = "https://placeholder.supabase.co"

        /**
         * Normalizes a raw Supabase project URL.
         * Gracefully handles:
         * - missing http/https scheme (prepends https://)
         * - trailing slashes (removes them for clean property storage)
         * - user accidentally swapping URL and anon key (e.g. pasting 'sb_pub...' in URL field)
         * - malformed URLs (falls back to safe placeholder URL so Retrofit/OkHttp never throws IllegalArgumentException)
         */
        fun normalizeUrl(rawUrl: String, fallbackAnonKey: String = ""): String {
            val trimmed = rawUrl.trim().removeSuffix("/")
            val trimmedKey = fallbackAnonKey.trim().removeSuffix("/")

            // 1. If rawUrl is blank, check if fallback key was actually the URL
            if (trimmed.isBlank()) {
                if (trimmedKey.startsWith("http://", ignoreCase = true) ||
                    trimmedKey.startsWith("https://", ignoreCase = true) ||
                    trimmedKey.contains(".supabase.co", ignoreCase = true)) {
                    return normalizeUrl(trimmedKey, "")
                }
                return DEFAULT_PLACEHOLDER_URL
            }

            // 2. If user accidentally placed API key (sb_pub... or JWT ey...) into URL field:
            if (trimmed.startsWith("sb_", ignoreCase = true) || trimmed.startsWith("ey", ignoreCase = true)) {
                // If anon key field contains a URL, swap them
                if (trimmedKey.startsWith("http://", ignoreCase = true) ||
                    trimmedKey.startsWith("https://", ignoreCase = true) ||
                    trimmedKey.contains(".supabase.co", ignoreCase = true)) {
                    return normalizeUrl(trimmedKey, "")
                }
                // Otherwise it's purely an API key and NOT a valid URL -> use placeholder so OkHttp/Retrofit never crashes
                return DEFAULT_PLACEHOLDER_URL
            }

            // 3. Ensure scheme exists
            val withScheme = when {
                trimmed.startsWith("http://", ignoreCase = true) || trimmed.startsWith("https://", ignoreCase = true) -> trimmed
                trimmed.contains(".") -> "https://$trimmed"
                else -> return DEFAULT_PLACEHOLDER_URL
            }

            val cleanUrl = withScheme.removeSuffix("/")

            // 4. Verify it parses cleanly with OkHttp HttpUrl
            return try {
                val parsed = "$cleanUrl/".toHttpUrlOrNull()
                if (parsed != null && (parsed.scheme == "http" || parsed.scheme == "https")) {
                    cleanUrl
                } else {
                    DEFAULT_PLACEHOLDER_URL
                }
            } catch (_: Exception) {
                DEFAULT_PLACEHOLDER_URL
            }
        }

        /**
         * Normalizes a raw Supabase API key / anon key.
         * Detects if user accidentally swapped key and URL.
         */
        fun normalizeKey(rawKey: String, fallbackUrlCandidate: String = ""): String {
            val trimmedKey = rawKey.trim()
            val trimmedUrl = fallbackUrlCandidate.trim()

            // If user swapped key and URL:
            if ((trimmedKey.startsWith("http://", ignoreCase = true) ||
                 trimmedKey.startsWith("https://", ignoreCase = true) ||
                 trimmedKey.contains(".supabase.co", ignoreCase = true)) &&
                (trimmedUrl.startsWith("sb_", ignoreCase = true) || trimmedUrl.startsWith("ey", ignoreCase = true))) {
                return trimmedUrl
            }
            return trimmedKey
        }

        /**
         * Checks whether the given credentials represent a real, non-placeholder, valid Supabase project.
         */
        fun isConfigured(url: String, key: String): Boolean {
            val normalizedUrl = normalizeUrl(url, key)
            val normalizedKey = normalizeKey(key, url)
            return normalizedUrl != DEFAULT_PLACEHOLDER_URL &&
                   !normalizedUrl.contains("placeholder.supabase.co") &&
                   !normalizedUrl.contains("sample-panchayat") &&
                   normalizedKey.isNotBlank() &&
                   !normalizedKey.contains("sample_anon_key")
        }

