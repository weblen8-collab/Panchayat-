        /**
         * Initializes the Supabase client in the application to enable database connectivity
         * and real-time features using the provided SUPABASE_URL and SUPABASE_ANON_KEY.
         *
         * @param context Application or activity context
         * @param supabaseUrl Supabase project base URL (defaults to BuildConfig.SUPABASE_URL)
         * @param supabaseAnonKey Supabase anonymous public key (defaults to BuildConfig.SUPABASE_ANON_KEY)
         * @param enableRealtime Whether to automatically connect the real-time WebSocket client (default: true)
         * @return Connected [SupabaseClient] instance
         */
        @JvmStatic
        @JvmOverloads
        fun initialize(
            context: Context? = null,
            supabaseUrl: String = BuildConfig.SUPABASE_URL,
            supabaseAnonKey: String = BuildConfig.SUPABASE_ANON_KEY,
            enableRealtime: Boolean = true
        ): SupabaseClient {
            if (context != null) {
                applicationContext = context.applicationContext
            }
            val client = configure(supabaseUrl, supabaseAnonKey)
            if (enableRealtime && client.isConfigured) {
                client.connectRealtime()
            }
            try {
                Log.d("SupabaseClient", "Initialized Supabase client with URL: ${client.supabaseUrl}, realtime enabled: $enableRealtime")
            } catch (_: Throwable) {}
            return client
        }

