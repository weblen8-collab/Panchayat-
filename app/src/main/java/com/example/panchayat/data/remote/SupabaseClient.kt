/**
 * Supabase client initialized and configured with SUPABASE_URL and SUPABASE_ANON_KEY
 * provided in the .env file (via BuildConfig generated by the Secrets Gradle Plugin)
 * to enable communication with the backend.
 */
class SupabaseClient(
    supabaseUrl: String = BuildConfig.SUPABASE_URL.trim(),
    supabaseAnonKey: String = BuildConfig.SUPABASE_ANON_KEY.trim()
) {

    val rawSupabaseUrl: String = supabaseUrl.trim()
    val rawSupabaseAnonKey: String = supabaseAnonKey.trim()

    val supabaseUrl: String = normalizeUrl(rawSupabaseUrl, rawSupabaseAnonKey)
    val supabaseAnonKey: String = normalizeKey(rawSupabaseAnonKey, rawSupabaseUrl)

    val formattedBaseUrl: String
        get() = if (supabaseUrl.endsWith("/")) supabaseUrl else "$supabaseUrl/"

    val isConfigured: Boolean
        get() = Companion.isConfigured(rawSupabaseUrl, rawSupabaseAnonKey)

    /**
     * Configuration object representing this client's URL and anon key settings.
     */
    val config: SupabaseConfig
        get() = SupabaseConfig(supabaseUrl, supabaseAnonKey)

    /**
     * Realtime WebSocket client configured for this Supabase project.
     * Connects to wss://<host>/realtime/v1/websocket?apikey=<anonKey>&vsn=1.0.0
     */
    val realtime: SupabaseRealtimeClient by lazy {
        SupabaseRealtimeClient(
            supabaseUrl = supabaseUrl,
            supabaseAnonKey = supabaseAnonKey,
            okHttpClient = okHttpClient
        )
    }

    /**
     * The official Supabase Realtime WebSocket endpoint URL.
     */
    val realtimeUrl: String
        get() = realtime.realtimeUrl

    /**
     * Observable connection state of the Realtime WebSocket client.
     */
    val realtimeStatus: StateFlow<RealtimeStatus>
        get() = realtime.status

    /**
     * Connects to Supabase Realtime for live database and broadcast event streaming.
     */
    fun connectRealtime(): SupabaseRealtimeClient {
        realtime.connect()
        return realtime
    }

    /**
     * Disconnects from Supabase Realtime.
     */
    fun disconnectRealtime() {
        realtime.disconnect()
    }

    /**
     * Subscribes to real-time events on the 'posts' table.
     */
    fun subscribeToPosts(
        onPostEvent: (table: String, eventType: String, payloadJson: String) -> Unit
    ): RealtimeChannel {
        return realtime.subscribeToPosts(onPostEvent)
    }

    /**
     * Interceptor providing the mandatory Supabase apikey and Bearer Authorization headers.
     */
    private val authInterceptor = Interceptor { chain ->
        val original: Request = chain.request()
        val request = original.newBuilder()
            .header("apikey", supabaseAnonKey)
            .header("Authorization", "Bearer $supabaseAnonKey")
            .header("Content-Type", "application/json")
            .header("Accept", "application/json")
            .method(original.method, original.body)
            .build()
        chain.proceed(request)
    }

    private val loggingInterceptor = HttpLoggingInterceptor().apply {
        level = HttpLoggingInterceptor.Level.BASIC
    }

    val okHttpClient: OkHttpClient by lazy {
        OkHttpClient.Builder()
            .addInterceptor(authInterceptor)
            .addInterceptor(loggingInterceptor)
            .connectTimeout(15, TimeUnit.SECONDS)
            .readTimeout(15, TimeUnit.SECONDS)
            .writeTimeout(15, TimeUnit.SECONDS)
            .retryOnConnectionFailure(true)
            .build()
    }

    val moshi: Moshi by lazy {
        Moshi.Builder()
            .add(KotlinJsonAdapterFactory())
            .build()
    }

    val retrofit: Retrofit by lazy {
        val safeBaseUrl = try {
            val parsed = formattedBaseUrl.toHttpUrlOrNull()
            if (parsed != null && (parsed.scheme == "http" || parsed.scheme == "https")) {
                formattedBaseUrl
            } else {
                DEFAULT_PLACEHOLDER_URL
            }
        } catch (_: Exception) {
            DEFAULT_PLACEHOLDER_URL
        }

        Retrofit.Builder()
            .baseUrl(safeBaseUrl)
            .client(okHttpClient)
            .addConverterFactory(MoshiConverterFactory.create(moshi))
            .build()
    }

    /**
     * Retrofit Supabase REST/PostgREST API service.
     */
    val api: SupabaseApi by lazy {
        retrofit.create(SupabaseApi::class.java)
    }

    /**
     * Retrofit Supabase GoTrue Auth API service.
     */
    val authApi: SupabaseAuthApi by lazy {
        retrofit.create(SupabaseAuthApi::class.java)
    }

    /**
     * Supabase Auth client for handling user sign up, sign in, and session management.
     */
    val auth: SupabaseAuthClient by lazy {
        SupabaseAuthClient(authApi, isConfigured)
    }

    /**
     * Helper method to sign up a user with email, password, and profile metadata.
     */
    suspend fun signUp(
        email: String,
        password: String,
        name: String = "",
        handle: String = ""
    ): Result<AuthResponse> {
        return auth.signUp(email, password, name, handle)
    }

    /**
     * Helper method to sign in a user with email and password.
     */
    suspend fun signIn(
        email: String,
        password: String
    ): Result<AuthResponse> {
        return auth.signIn(email, password)
    }

    /**
     * Helper method to sign out the current user.
     */
    suspend fun signOut(): Result<Unit> {
        return auth.signOut()
    }

    /**
     * Helper method to fetch posts directly from Supabase backend.
     */
    suspend fun getPosts(limit: Int = 50): Response<List<SupabasePostDto>> {
        return api.getPosts(limit = limit)
    }

    /**
     * Helper method to fetch domain Post models directly from the Supabase 'posts' table.
     */
    suspend fun fetchPosts(limit: Int = 50): Result<List<com.example.panchayat.data.model.Post>> {
        return try {
            val response = api.getPostModels(limit = limit)
            if (response.isSuccessful) {
                val posts = response.body() ?: emptyList()
                Result.success(posts)
            } else {
                // Fallback to DTO parsing if necessary
                val dtoResponse = api.getPosts(limit = limit)
                if (dtoResponse.isSuccessful) {
                    val dtos = dtoResponse.body() ?: emptyList()
                    Result.success(dtos.map { com.example.panchayat.data.model.Post.fromDto(it) })
                } else {
                    Result.failure(Exception("Supabase posts error HTTP ${response.code()}: ${response.message()}"))
                }
            }
        } catch (e: Exception) {
            Log.e("SupabaseClient", "Failed to fetch posts from Supabase: ${e.message}", e)
            Result.failure(e)
        }
    }

    /**
     * Helper method to create/publish a new post on Supabase backend.
     */
    suspend fun createPost(post: SupabasePostDto): Response<List<SupabasePostDto>> {
        return api.createPost(post)
    }

    /**
     * Helper method to insert a domain Post model into the Supabase 'posts' table.
     */
    suspend fun insertPost(post: com.example.panchayat.data.model.Post): Result<com.example.panchayat.data.model.Post> {
        return try {
            val response = api.insertPost(post)
            val inserted = if (response.isSuccessful && !response.body().isNullOrEmpty()) {
                response.body()!!.first()
            } else {
                val dtoResponse = api.createPost(
                    SupabasePostDto(
                        id = post.id,
                        authorId = post.authorId,
                        authorName = post.authorName,
                        authorHandle = post.authorHandle,
                        authorAvatarUrl = post.authorAvatarUrl,
                        isVerified = post.isVerified,
                        content = post.content,
                        category = post.category,
                        mediaUrl = post.mediaUrl,
                        likesCount = post.likesCount,
                        repostsCount = post.repostsCount,
                        repliesCount = post.commentsCount,
                        viewsCount = post.viewsCount
                    )
                )
                if (dtoResponse.isSuccessful && !dtoResponse.body().isNullOrEmpty()) {
                    com.example.panchayat.data.model.Post.fromDto(dtoResponse.body()!!.first())
                } else {
                    return Result.failure(Exception("Failed to insert post: HTTP ${response.code()} ${response.message()}"))
                }
            }
            realtime.dispatchLocalEvent(
                topic = "realtime:public:posts",
                event = "INSERT",
                payloadJson = """{"id":"${inserted.id}","content":"${inserted.content.replace("\"", "\\\"")}","author_name":"${inserted.authorName}"}"""
            )
            Result.success(inserted)
        } catch (e: Exception) {
            Log.e("SupabaseClient", "Failed to insert post into Supabase: ${e.message}", e)
            Result.failure(e)
        }
    }

    /**
     * Fetches user profile from Supabase 'profiles' table.
     */
    suspend fun fetchUserProfile(userId: String? = null): Result<com.example.panchayat.data.model.UserProfile?> {
        return try {
            val response = api.getProfiles()
            if (response.isSuccessful) {
                val list = response.body() ?: emptyList()
                val profileDto = when {
                    !userId.isNullOrBlank() -> list.find { it.id == userId || it.handle.equals(userId, ignoreCase = true) }
                    auth.currentUser.value != null -> list.find {
                        it.id == auth.currentUser.value?.id ||
                        it.handle.equals(auth.currentUser.value?.email?.substringBefore("@"), ignoreCase = true)
                    }
                    else -> list.find { it.id == "user_me" } ?: list.firstOrNull()
                }
                Result.success(profileDto?.toUserProfile())
            } else {
                Result.failure(Exception("Failed to fetch profile from Supabase: HTTP ${response.code()} ${response.message()}"))
            }
        } catch (e: Exception) {
            Log.e("SupabaseClient", "Failed to fetch user profile: ${e.message}", e)
            Result.failure(e)
        }
    }

    /**
     * Upserts a user profile into the Supabase 'profiles' table.
     */
    suspend fun upsertUserProfile(profile: com.example.panchayat.data.model.UserProfile): Result<com.example.panchayat.data.model.UserProfile> {
        return try {
            val dto = SupabaseProfileDto(
                id = profile.id,
                name = profile.name,
                handle = profile.handle,
                bio = profile.bio,
                location = profile.location,
                joinedDate = profile.joinedDate,
                followingCount = profile.followingCount,
                followersCount = profile.followersCount,
                isVerified = profile.isVerified,
                avatarUrl = profile.avatarUrl
            )
            val response = api.upsertProfile(dto)
            if (response.isSuccessful) {
                val updated = response.body()?.firstOrNull()?.toUserProfile() ?: profile
                Result.success(updated)
            } else {
                Result.failure(Exception("Failed to upsert profile to Supabase: HTTP ${response.code()} ${response.message()}"))
            }
        } catch (e: Exception) {
            Log.e("SupabaseClient", "Failed to upsert profile: ${e.message}", e)
            Result.failure(e)
        }
    }

    /**
     * Fetches past microblog posts created by a specific user from the Supabase backend.
     */
    suspend fun fetchUserPosts(
        authorId: String? = null,
        authorHandle: String? = null,
        limit: Int = 50
    ): Result<List<com.example.panchayat.data.model.Post>> {
        return try {
            val allPostsResult = fetchPosts(limit = limit)
            if (allPostsResult.isSuccess) {
                val allPosts = allPostsResult.getOrNull() ?: emptyList()
                val filtered = allPosts.filter { post ->
                    val idMatch = authorId != null && (post.authorId == authorId || (authorId == "user_me" && post.authorId == "user_me"))
                    val handleMatch = authorHandle != null && post.authorHandle.equals(authorHandle, ignoreCase = true)
                    val defaultMeMatch = (authorId == null || authorId == "user_me") && post.authorId == "user_me"
                    idMatch || handleMatch || defaultMeMatch
                }
                Result.success(filtered)
            } else {
                allPostsResult
            }
        } catch (e: Exception) {
            Log.e("SupabaseClient", "Failed to fetch user posts: ${e.message}", e)
            Result.failure(e)
        }
    }

    /**
     * Increments the like count for a specific post in the Supabase 'posts' table.
     *
     * @param postId The unique ID of the post
     * @param currentLikesCount The current like count of the post before incrementing
     * @return Result containing the updated like count
     */
    suspend fun incrementPostLikes(postId: String, currentLikesCount: Int): Result<Int> {
        val targetCount = currentLikesCount + 1
        return try {
            val response = api.updatePostLikes(
                idFilter = "eq.$postId",
                body = SupabaseUpdateLikesDto(likesCount = targetCount)
            )
            if (response.isSuccessful) {
                val updatedCount = response.body()?.firstOrNull()?.likesCount ?: targetCount
                Log.d("SupabaseClient", "Successfully incremented likes for post $postId to $updatedCount")
                realtime.dispatchLocalEvent(
                    topic = "realtime:public:posts",
                    event = "UPDATE",
                    payloadJson = """{"id":"$postId","likes_count":$updatedCount}"""
                )
                Result.success(updatedCount)
            } else {
                Log.w("SupabaseClient", "Supabase like update returned HTTP ${response.code()}: ${response.message()}")
                if (!isConfigured) {
                    Result.success(targetCount)
                } else {
                    Result.failure(Exception("Supabase like update failed HTTP ${response.code()}: ${response.message()}"))
                }
            }
        } catch (e: Exception) {
            Log.e("SupabaseClient", "Failed to increment likes on Supabase: ${e.message}", e)
            if (!isConfigured) {
                Result.success(targetCount)
            } else {
                Result.failure(e)
            }
        }
    }

    /**
     * Updates the like count directly for a specific post in the Supabase 'posts' table.
     */
    suspend fun updatePostLikes(postId: String, likesCount: Int): Result<Int> {
        return try {
            val response = api.updatePostLikes(
                idFilter = "eq.$postId",
                body = SupabaseUpdateLikesDto(likesCount = likesCount)
            )
            if (response.isSuccessful) {
                val updatedCount = response.body()?.firstOrNull()?.likesCount ?: likesCount
                Result.success(updatedCount)
            } else {
                if (!isConfigured) {
                    Result.success(likesCount)
                } else {
                    Result.failure(Exception("Supabase like update failed HTTP ${response.code()}: ${response.message()}"))
                }
            }
        } catch (e: Exception) {
            Log.e("SupabaseClient", "Failed to update likes on Supabase: ${e.message}", e)
            if (!isConfigured) {
                Result.success(likesCount)
            } else {
                Result.failure(e)
            }
        }
    }

    /**
     * Toggles the like state of a post and updates the likes count in the Supabase 'posts' table.
     */
    suspend fun togglePostLike(
        postId: String,
        currentLikesCount: Int,
        currentlyLiked: Boolean
    ): Result<Pair<Boolean, Int>> {
        val newLiked = !currentlyLiked
        val targetCount = if (newLiked) currentLikesCount + 1 else maxOf(0, currentLikesCount - 1)
        val updateResult = updatePostLikes(postId, targetCount)
        return if (updateResult.isSuccess) {
            val confirmedCount = updateResult.getOrDefault(targetCount)
            realtime.dispatchLocalEvent(
                topic = "realtime:public:posts",
                event = "UPDATE",
                payloadJson = """{"id":"$postId","likes_count":$confirmedCount}"""
            )
            Result.success(Pair(newLiked, confirmedCount))
        } else {
            if (!isConfigured) {
                Result.success(Pair(newLiked, targetCount))
            } else {
                Result.failure(updateResult.exceptionOrNull() ?: Exception("Failed to update likes in Supabase"))
            }
        }
    }

    /**
     * Helper to like or update likes for a post.
     */
    suspend fun likePost(postId: String, likesCount: Int = 1): Result<Int> {
        return updatePostLikes(postId, likesCount)
    }

    /**
     * Helper to record or toggle reposts for a post.
     */
    suspend fun repost(postId: String, repostsCount: Int = 1): Result<Int> {
        return Result.success(repostsCount)
